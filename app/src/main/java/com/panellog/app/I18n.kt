    fun t(key: String): String = T[key]?.let { if (he) it.second else it.first } ?: key
    fun f(key: String, vararg args: Any?): String = String.format(t(key), *args)

    /** Текст панели (иврит/англ.) + перевод, если интерфейс русский. */
    fun panel(s: String): String {
        if (he || s.isEmpty()) return s
        val ru = PanelDecoder.ru(s) ?: return s
        return "$s — $ru"
    }

    fun devType(t: String): String {
        if (t.isEmpty()) return ""
        val h = PanelDecoder.typeHe(t)
        if (he) return h
        val r = PanelDecoder.typeRu(t)
        return if (r != null) "$h ($r)" else h
    }
